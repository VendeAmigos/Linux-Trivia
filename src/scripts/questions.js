/**
 * Returns a mixed array of questions matching the difficulty curve.
 * 
 * @param {string} difficulty - 'easy', 'normal', 'hard'
 * @param {number} totalQuestions - number of questions to return
 * @returns {Array} Shuffled and mixed array of questions
 */
export function getMixedQuestions(difficulty, totalQuestions) {
  let pool = [];

  // Clone pools to avoid mutating original arrays
  const easyPool = [...questions.easy];
  const normalPool = [...questions.normal];
  const hardPool = [...questions.hard];

  // Shuffle pools
  easyPool.sort(() => Math.random() - 0.5);
  normalPool.sort(() => Math.random() - 0.5);
  hardPool.sort(() => Math.random() - 0.5);

  if (difficulty === 'easy') {
    pool = [...easyPool.slice(0, totalQuestions)];
  } else if (difficulty === 'normal') {
    // 40% easy, 60% normal
    const eCount = Math.floor(totalQuestions * 0.4);
    const nCount = totalQuestions - eCount;
    pool = [...easyPool.slice(0, eCount), ...normalPool.slice(0, nCount)];
  } else if (difficulty === 'hard') {
    // 30% normal, 70% hard
    const nCount = Math.floor(totalQuestions * 0.3);
    const hCount = totalQuestions - nCount;
    pool = [...normalPool.slice(0, nCount), ...hardPool.slice(0, hCount)];
  }

  // Final shuffle of the mixed pool
  return pool.sort(() => Math.random() - 0.5);
}
